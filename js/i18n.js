export const LANGUAGES = [
  { code: 'en', label: 'English', short: 'EN', dir: 'ltr' },
  { code: 'fa', label: 'فارسی', short: 'فا', dir: 'rtl' },
  { code: 'ar', label: 'العربية', short: 'ع', dir: 'rtl' },
];

const dictionaries = { en, fa, ar };
const LANG_KEY = 'azs.lang';

function initialLang() {
  try {
    const saved = localStorage.getItem(LANG_KEY);
    if (dictionaries[saved]) return saved;
  } catch { /* storage unavailable */ }
  const nav = (navigator.language || '').toLowerCase().slice(0, 2);
  return dictionaries[nav] ? nav : 'en';
}

let lang = initialLang();

export const getLang = () => lang;
export const langInfo = (code = lang) => LANGUAGES.find((l) => l.code === code);
export const isRtl = () => langInfo().dir === 'rtl';

export function setLang(next) {
  if (!dictionaries[next]) return;
  lang = next;
  try { localStorage.setItem(LANG_KEY, next); } catch { /* ignore */ }
  applyLang();
}

export function applyLang() {
  document.documentElement.lang = lang;
  document.documentElement.dir = langInfo().dir;
}

/** Localised digits: Persian digits in fa, Arabic-Indic digits in ar, Latin in en. */
export function localDigits(s) {
  if (lang === 'fa') return toPersianDigits(s);
  if (lang === 'ar') return toArabicDigits(s);
  return String(s);
}

/** Localised, grouped number. */
export function num(n) {
  const s = typeof n === 'number' ? n.toLocaleString('en-US') : String(n);
  return lang === 'en' ? s : localDigits(s.replace(/,/g, '٬'));
}

export function t(key, vars) {
  let s = dictionaries[lang][key] ?? dictionaries.en[key];
  if (s === undefined) {
    console.warn(`[i18n] missing key: ${key}`);
    return key;
  }
  if (vars) s = s.replace(/\{(\w+)\}/g, (_, k) => (vars[k] ?? ''));
  return s;
}

/** Message for an API error code, falling back to a generic message. */
export function errorText(code, vars) {
  return dictionaries.en[`err.${code}`] ? t(`err.${code}`, vars) : t('err.GENERIC');
}

/** Dev aid: keys present in English but missing from another dictionary. */
export function missingKeys() {
  const out = {};
  for (const [code, dict] of Object.entries(dictionaries)) {
    const missing = Object.keys(en).filter((k) => !(k in dict));
    if (missing.length) out[code] = missing;
  }
  return out;
}

